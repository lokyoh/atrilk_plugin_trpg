    def active_tools(self, values: Mapping[str, Any]) -> tuple[type[AgentTool], ...]:
        """剧情 / 战斗各用各的功能子集（22 个全给会白烧 token，也容易误调用）。"""
        in_combat = bool(str(values.get("combat", "") or "").strip())
        hidden = _STORY_ONLY_TOOLS if in_combat else _COMBAT_ONLY_TOOLS
        return tuple(tool for tool in self.tools if tool.function_name not in hidden)

    def compose_system(self, values: Mapping[str, Any]) -> str:
        """拼系统提示词：通用原则 + （战斗规则 | 剧情规则）。"""
        in_combat = bool(str(values.get("combat", "") or "").strip())
        mode_rules = _COMBAT_RULES if in_combat else _STORY_RULES
        return f"{_DM_CORE}\n\n{mode_rules}"

    def build_messages(self, values: Mapping[str, Any]) -> LLMMessages:
        """系统提示词（按模式 + 该模式的功能子集）+ 用户输入。"""
        messages = LLMMessages()
        system = self.compose_system(values).strip()
        tools = self.active_tools(values)
        if tools:
            function_prompt = self.function_prompt(tools)
            system = f"{system}\n\n{function_prompt}" if system else function_prompt
        if system:
            messages.add_message(LLMMessage("system", LLMContents().text(system)))
        messages.add_message(
            LLMMessage("user", LLMContents().text(self.build_prompt(values)))
        )
        return messages


