"""跑团 Agent：城镇据点详细生成（city）。

对应 ``.agents/new_plusin_lktrpg.md`` 的「DM Agent 入场流程」，
提示词精简自 ``.agents/trpg/generate_city.md``。

根据据点基础数据，生成一份据点（城镇 / 要塞 / 村落等）详细文档，为后续建立场景提供依据：
可探索的具体场所、可触发的场景与线索。落库由调用方负责（世界库 ``city`` / 据点名）。
"""

from __future__ import annotations

from ..base import AgentInput, TrpgAgent

__all__ = ["CityAgent", "city_agent"]


_SYSTEM_PROMPT = """# 任务
根据已有的据点基础数据，为该据点生成一份详细信息文档，为后续建立场景提供依据，包括：可探索的具体场所、可触发的场景与线索。

# 输入
据点基础数据，格式如下：
```markdown
### 据点：<名称>
- 据点类型：
- 地理位置：
- 面积：
- 人口：
- 势力归属：
- 势力结构：
- 经济基础：
- 军事力量：
- 与周边的关系：
- 特殊之处：
```

# 输出
一份 Markdown 文档，含十节：据点概览、空间布局、重要场所、人口与社会、势力与权力、经济与资源、军事与防御、周边关系、特殊之处、场景线索。

# 输出模板
```markdown
# 地点详细文档：<据点名称>

## 一、据点概览
- 据点名称：
- 据点类型：
- 一句话定位：
- 整体印象：
- 在区域中的角色：

## 二、空间布局
- 整体形状：
- 边界与入口：
- 主要分区：
- 道路与交通：
- 地标建筑：
- 与地形的关系：
- 防御布局：

## 三、重要场所
### 场所：<名称>
- 场所类型：
- 位置：
- 外观：
- 内部空间：
- 氛围：
- 功能：
- 所属势力：
- 常驻人员：
- 秘密与线索：
- 场景可能：
（可重复多个场所）

## 四、人口与社会
- 人口数量：
- 种族构成：
- 职业构成：
- 阶层结构：
- 日常生活：
- 语言与信仰：
- 治安状况：
- 社会矛盾：

## 五、势力与权力
- 统治形式：
- 统治者：
- 权力机构：
- 主要派系：
- 派系关系：
- 权力斗争：
- 外部势力影响：

## 六、经济与资源
- 主要产业：
- 主要资源：
- 贸易对象：
- 货币与物价：
- 市场与商会：
- 税收与徭役：
- 经济矛盾：

## 七、军事与防御
- 驻军规模：
- 兵种构成：
- 指挥官：
- 防御工事：
- 巡逻与警戒：
- 军事威胁：

## 八、周边关系
- 与邻近据点的关系：
- 与所属地区的关系：
- 与相邻地区的关系：
- 交通线与关隘：
- 情报与谣言：

## 九、特殊之处
- 具体表现：
- 形成原因：
- 对据点的影响：
- 对来访者的影响：
- 隐藏的秘密：

## 十、场景线索
### 场景：<名称>
- 触发条件：
- 涉及场所：
- 场景内容：
- 可能走向（至少三种）：
（可重复多个场景）
```

# 生成要求
- 所有内容必须基于已有的据点基础数据、地区信息；不新增未提及的国家、地区或势力。
- 空间布局、重要场所、人口、势力、经济、军事之间需逻辑自洽。
- 场景线索需与已有设定对应；场景是「可能性」，不是「必经剧情」。
- 语言简洁、结构化，可直接用于后续建立场景。"""


class CityAgent(TrpgAgent):
    """城镇据点详细生成：产出据点的详细文档与场景线索。"""

    name = "city"
    title = "城镇据点详细生成"
    description = "根据据点基础数据，生成据点详细文档与可触发的场景线索"
    system_prompt = _SYSTEM_PROMPT
    inputs = (
        AgentInput("settlement", "据点基础数据", description="据点：<名称> 及其字段"),
        AgentInput(
            "context",
            "所在区域信息",
            required=False,
            description="该据点所在地区的信息，供保持一致，可留空",
        ),
        AgentInput(
            "bible",
            "世界圣经",
            required=False,
            description="世界专有名词与事实的登记；命名与事实以它为准，可留空",
        ),
    )


#: 全局默认实例
city_agent = CityAgent()
