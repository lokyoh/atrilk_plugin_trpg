"""DND 专属内容。

基础能力（骰子、检定、角色基类、规则判断器基类）继承自 :mod:`..trpg`，
本包只放 DND 5e 的数据表与规则实现：

- :mod:`attributes` 六大属性与调整值
- :mod:`skills` 十八项技能
- :mod:`race` 种族与亚种
- :mod:`profession` 职业（生命骰、豁免、技能池、装备包）
- :mod:`background` 背景
- :mod:`equipment` 护甲 / 武器 / 装备栈
- :mod:`spells` 法术数据表（0~3 环 + 法术位表）
- :mod:`monsters` 怪物数据表（AC / 生命 / 攻击 / 特性）
- :mod:`npcs` 人形 NPC 档位表（按队伍等级给数值）与 NPC 名单（旧伤 / 关系）
- :mod:`card` 角色卡（组装 + 检定 + 倒地与死亡豁免）
- :mod:`combat` 战斗状态（先攻顺序 + 当前回合 + 敌人个体 + 行动经济记账）
- :mod:`storage` 角色卡落盘
- :mod:`session_store` 建卡会话落盘（超出 ``session_expire_timeout`` 也能续接）
- :mod:`world_store` 全局共享世界文档库（world / 剧情 / 地点等，markdown + JSON 索引）
- :mod:`save_store` 跑团存档（角色卡副本 + 进度 + 事件日志）
- :mod:`judge` 规则判断器
- :mod:`creation` 建卡流程状态机
"""

